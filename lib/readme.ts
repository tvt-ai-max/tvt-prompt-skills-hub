import type { HubItem } from '@/types/hub';
import { categoryLabel, TIER_META } from '@/lib/labels';
import { itemCategory } from '@/lib/summary';

export const INDEX_START = '<!-- DIRECTORY-INDEX:START — generated by `npm run readme`, do not edit by hand -->';
export const INDEX_END = '<!-- DIRECTORY-INDEX:END -->';

const TIER_EMOJI = { prompt: '✨', skill: '🤖', boost: '🧠' } as const;

function cell(text: string, max = 110) {
  const clean = text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  return clean.length > max ? `${clean.slice(0, max - 1).trimEnd()}…` : clean;
}

function anchor(tier: string, category: string) {
  return `${tier}-${category}`.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
}

/** Markdown "Curated Directory Index" for README — grouped by tier then category, with stable anchors. */
export function buildReadmeIndex(items: HubItem[], sources: Record<string, string>, siteUrl: string): string {
  const site = siteUrl.replace(/\/$/, '');
  const out: string[] = [INDEX_START, ''];
  const tiers = (['prompt', 'skill', 'boost'] as const).map((tier) => {
    const list = items.filter((i) => i.tier === tier);
    const byCategory = new Map<string, HubItem[]>();
    for (const item of list) {
      const key = itemCategory(item);
      byCategory.set(key, [...(byCategory.get(key) ?? []), item]);
    }
    const groups = [...byCategory].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));
    return { tier, list, groups };
  });

  out.push(`**${items.length} tài sản** · ${tiers.map((t) => `${t.list.length} ${TIER_META[t.tier].plural}`).join(' · ')}`, '');
  out.push('| Tầng | Chuyên khoa | Số lượng |', '|---|---|---:|');
  for (const { tier, groups } of tiers) {
    for (const [category, group] of groups) {
      out.push(`| ${TIER_EMOJI[tier]} ${TIER_META[tier].plural} | [${categoryLabel(category)}](#${anchor(tier, category)}) | ${group.length} |`);
    }
  }
  out.push('');

  for (const { tier, list, groups } of tiers) {
    if (!list.length) continue;
    out.push(`### ${TIER_EMOJI[tier]} ${TIER_META[tier].plural} (${list.length})`, '');
    for (const [category, group] of groups) {
      out.push(`<a id="${anchor(tier, category)}"></a>`, '', `#### ${categoryLabel(category)} (${group.length})`, '');
      out.push(tier === 'boost' ? '| Boost | Lệnh | Mô tả | Nguồn |' : '| Tên | Mô tả | Nguồn |');
      out.push(tier === 'boost' ? '|---|---|---|---|' : '|---|---|---|');
      for (const item of [...group].sort((a, b) => a.title.localeCompare(b.title))) {
        const name = `[${cell(item.title, 80)}](${site}/items/${item.id})`;
        const src = sources[item.id] ? `[📄](${sources[item.id]})` : '';
        out.push(
          item.tier === 'boost'
            ? `| ${name} | \`${item.slashCommand}\` | ${cell(item.description)} | ${src} |`
            : `| ${name} | ${cell(item.description)} | ${src} |`,
        );
      }
      out.push('');
    }
  }
  out.push(INDEX_END);
  return out.join('\n');
}

/** Replaces the block between the markers (or appends it). */
export function injectIndex(readme: string, index: string): string {
  const start = readme.indexOf(INDEX_START);
  const end = readme.indexOf(INDEX_END);
  if (start === -1 || end === -1 || end < start) return `${readme.trimEnd()}\n\n${index}\n`;
  return readme.slice(0, start) + index + readme.slice(end + INDEX_END.length);
}
